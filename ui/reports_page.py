    def load_reports(self):
        """Initiate database fetch with loading overlay spinner simulated."""
        self.stacked_view.setCurrentIndex(1) # Loading view
        self.search_btn.setEnabled(False)
        self.reset_btn.setEnabled(False)
        
        # Fetch matching rows after a tiny layout update delay (simulates professional load animation)
        QtCore.QTimer.singleShot(250, self.fetch_data_from_db)

    def fetch_data_from_db(self):
        try:
            mat = self.filter_material.text().strip()
            op = self.filter_operator.text().strip()
            dt = self.filter_date.text().strip()
            smp = self.filter_sample.text().strip()
            tst = self.filter_test.text().strip()
            
            raw_reports = self.report_manager.get_reports_filtered(
                material=mat,
                username=op,
                date_str=dt,
                sample_name=smp,
                test_name=tst
            )
            
            # Map database list to structured dicts
            self.all_reports = []
            for r in raw_reports:
                self.all_reports.append({
                    'id': r[0],
                    'username': r[1],
                    'gauge_length': r[2] if r[2] else 0.0,
                    'initial_distance': r[3] if r[3] else 0.0,
                    'final_distance': r[4] if r[4] else 0.0,
                    'strain': r[5] if r[5] else 0.0,
                    'created_at': r[6] if r[6] else "",
                    'material': r[7] if r[7] else "N/A",
                    'sample_name': r[8] if r[8] else "N/A",
                    'test_name': r[9] if r[9] else "N/A",
                    'operator': r[10] if r[10] else (r[1] if r[1] else "N/A"),
                    'remarks': r[11] if r[11] else "",
                    'camera_resolution': r[12] if r[12] else "Unknown",
                    'software_version': r[13] if r[13] else "v2.5.0"
                })
            
            self.update_statistics()
            if hasattr(self, 'keep_page_on_reload') and self.keep_page_on_reload:
                total = len(self.all_reports)
                total_pages = max(1, math.ceil(total / self.items_per_page))
                if self.current_page > total_pages:
                    self.current_page = total_pages
                self.keep_page_on_reload = False
            else:
                self.current_page = 1
            self.refresh_table_view()
            
        except Exception as e:
            print(f"[ERROR] Failed to query reports: {e}")
            CustomDialog.critical(self, "Query Error", "Failed to load reports from database.", details=str(e))
            self.stacked_view.setCurrentIndex(2) # Fallback to empty/error representation
            
        finally:
            self.search_btn.setEnabled(True)
            self.reset_btn.setEnabled(True)

    def _animate_kpi_value(self, label):
        effect = QtWidgets.QGraphicsOpacityEffect(label)
        label.setGraphicsEffect(effect)
        anim = QtCore.QPropertyAnimation(effect, b"opacity", label)
        anim.setDuration(180)
        anim.setStartValue(0.55)
        anim.setEndValue(1.0)
        anim.start(QtCore.QAbstractAnimation.DeleteWhenStopped)

    def _kpi_value_style(self, label, *, placeholder=False):
        if label is self.val_avg_strain:
            if placeholder:
                return "font-size: 13px; font-weight: 600; color: #64748b;"
            return "font-size: 32px; font-weight: bold; color: #fbbf24;"
        return "font-size: 32px; font-weight: bold; color: #f8fafc;"

    def _set_kpi_value(self, label, text, *, placeholder=False):
        style = self._kpi_value_style(label, placeholder=placeholder)
        if label.text() != text or label.styleSheet() != style:
            label.setText(text)
            label.setStyleSheet(style)
            self._animate_kpi_value(label)

    def _fetch_total_report_count(self):
        cur = self.report_manager.db.conn.cursor()
        cur.execute("SELECT COUNT(*) FROM reports")
        count = cur.fetchone()[0]
        cur.close()
        return count

    def _report_by_id(self, report_id):
        for report in self.all_reports:
            if report["id"] == report_id:
                return report
        return None

    def _selected_report_strains(self):
        strains = []
        selected_rows = sorted({index.row() for index in self.table.selectedIndexes()})
        for row in selected_rows:
            id_item = self.table.item(row, 0)
            if not id_item:
                continue
            try:
                report_id = int(id_item.text())
            except ValueError:
                continue
            report = self._report_by_id(report_id)
            if report is not None:
                strains.append(report["strain"])
        return strains

    def on_table_selection_changed(self):
        self.update_average_strain_from_selection()

    def update_total_reports(self):
        try:
            total = self._fetch_total_report_count()
            self._set_kpi_value(self.val_total, str(total))
        except Exception as e:
            print(f"[ERROR] Failed to update total reports KPI: {e}")

    def update_average_strain_from_selection(self):
        strains = self._selected_report_strains()
        if not strains:
            placeholder = "Select Report" if self.all_reports else "—"
            self._set_kpi_value(self.val_avg_strain, placeholder, placeholder=True)
            return
        avg_strain = sum(strains) / len(strains)
        self._set_kpi_value(
            self.val_avg_strain,
            f"{avg_strain * 100:+.3f} %",
            placeholder=False,
        )

