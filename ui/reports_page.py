class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas renderer that dynamically calculates the total page count
    and draws a professional footer bar with page numbers, generation time,
    and software version details on every page.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_footer(num_pages)
            super().showPage()
        super().save()

    def draw_footer(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 45, 558, 45)

        profile = CompanyManager.get_instance().get_profile()
        footer_text = (profile.get("footer_text") or "").replace("\n", "  |  ")
        version_text = "Software Version: v2.5.0-industrial"
        gen_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        footer_left = footer_text or "Generated by Video Extensometer Software"
        footer_left = f"{footer_left}  |  {version_text}"
        footer_right = f"{gen_time}  |  Page {self._pageNumber} of {page_count}"

        self.drawString(54, 30, footer_left[:120])
        self.drawRightString(558, 30, footer_right)

        self.restoreState()


